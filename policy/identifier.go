package policy

// validIdentifier reports whether s is a valid tool or argument name: 1 to 64
// ASCII bytes from A-Z, a-z, 0-9, underscore, dot and hyphen.
func validIdentifier(s string) bool {
	if len(s) == 0 || len(s) > 64 {
		return false
	}
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case c >= 'A' && c <= 'Z':
		case c >= 'a' && c <= 'z':
		case c >= '0' && c <= '9':
		case c == '_' || c == '.' || c == '-':
		default:
			return false
		}
	}
	return true
}
